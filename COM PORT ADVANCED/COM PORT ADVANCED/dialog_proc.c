// =============================================================================
// dialog_proc.c — Главный файл логики диалогового окна
//
// Что делает эта программа:
//   Открывает диалоговое окно Windows, в котором отображается список всех
//   COM-портов, подключённых к компьютеру. Для каждого порта показывается:
//     - Hardware ID  (уникальный идентификатор устройства в системе)
//     - Friendly Name (читаемое название, например "USB Serial Port (COM3)")
//     - Имя порта    (например "COM3")
//     - Статус       (Free = свободен, Busy = занят другой программой)
//
// Архитектура:
//   Главный поток  → создаёт окно, обрабатывает сообщения Windows
//   Фоновый поток  → опрашивает SetupAPI, отправляет результаты в окно
//   Связь между ними → PostMessage(WM_POPULATE) — безопасный способ
//   передачи данных из фонового потока в GUI
// =============================================================================

// windows.h — главный заголовок WinAPI, подключает сотни функций и типов
#include <windows.h>

// setupapi.h — функции для работы с устройствами (SetupDiGetClassDevs и др.)
#include <setupapi.h>

// devguid.h — содержит GUID_DEVCLASS_PORTS — уникальный идентификатор
// класса устройств "Ports" (COM и LPT порты) в реестре Windows
#include <devguid.h>

// wctype.h — функция towupper() для перевода Unicode-символа в верхний регистр
#include <wctype.h>

// Наши собственные заголовочные файлы:
#include "resource.h"    // константы ресурсов (ID_LOG, IDC_BTN_REFRESH и т.д.)
#include "dialog_proc.h" // объявление MainDialogProc и WM_POPULATE

// Говорим компоновщику (linker) автоматически подключить библиотеки.
// Без них функции SetupDi* просто не найдутся при сборке.
#pragma comment(lib, "setupapi.lib")
#pragma comment(lib, "user32.lib")
#pragma comment(lib, "kernel32.lib")

