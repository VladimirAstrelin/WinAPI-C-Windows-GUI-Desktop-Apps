// custom_controls.h – заголовочный файл для модуля создания пользовательских контролов.
// Здесь мы объявляем функцию CreateStatusBar, которую будем использовать в диалоге.

#pragma once

#include <windows.h>      // Основные типы
#include <commctrl.h>     // Заголовок для общих элементов управления (статус-бар, панели инструментов).
                          // Он содержит определения STATUSCLASSNAME, SB_SETTEXT, SB_SETPARTS и др.

// Функция для создания статусной панели с заданным количеством частей.
// Возвращает HWND созданной панели или NULL при ошибке.
// Параметры:
//   hwndParent  – дескриптор родительского окна (диалога)
//   hInst       – дескриптор экземпляра приложения (для создания окна)
//   partsCount  – количество частей (панелей) в статусной строке
//   partsWidths – массив целых чисел, задающих ширину каждой части (в пикселях).
//                 Последняя часть обычно имеет ширину -1, чтобы занять всё оставшееся место.
HWND CreateStatusBar(HWND hwndParent, HINSTANCE hInst, int partsCount, const int* partsWidths);