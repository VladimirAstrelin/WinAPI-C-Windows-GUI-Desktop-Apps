// custom_controls.c – реализация функций для работы с пользовательскими контролами.
// В данном файле мы создаём статусную панель – это стандартный элемент Windows,
// но мы оборачиваем его в нашу функцию для удобства и переиспользования.

#include "custom_controls.h"   // Собственный заголовок
#include <commctrl.h>          // Уже включён в заголовке, но продублируем для надёжности

// Подключаем библиотеку comctl32.lib к проекту.
// Это необходимо, потому что функции InitCommonControlsEx и константы статус-бара
// находятся именно в этой библиотеке. Без этой строки возникает ошибка линковки LNK2019.
#pragma comment(lib, "comctl32.lib")

// Реализация функции создания статусной панели.
HWND CreateStatusBar(HWND hwndParent, HINSTANCE hInst, int partsCount, const int* partsWidths)
{
    // Структура для инициализации общих элементов управления.
    // Мы должны заполнить её перед вызовом InitCommonControlsEx.
    INITCOMMONCONTROLSEX icex;

    // Указываем размер структуры – обязательно, чтобы система знала, какая версия.
    icex.dwSize = sizeof(INITCOMMONCONTROLSEX);

    // Флаги, указывающие, какие классы элементов нам нужны.
    // ICC_BAR_CLASSES включает статус-бар, панель инструментов, прогресс-бар и др.
    // Если бы мы использовали только статус-бар, можно было бы использовать ICC_BAR_CLASSES.
    icex.dwICC = ICC_BAR_CLASSES;

    // Вызов InitCommonControlsEx – загружает библиотеку общих контролов.
    // Если инициализация не удалась (возвращает FALSE), то создание статус-бара невозможно.
    if (!InitCommonControlsEx(&icex))
        return NULL;

    // Создаём окно статусной панели с помощью CreateWindowEx.
    // STATUSCLASSNAME – это предопределённое имя класса для статус-бара (строка "msctls_statusbar32").
    HWND hwndStatus = CreateWindowEx(
        0,                     // Расширенные стили – не используем
        STATUSCLASSNAME,       // Имя класса
        NULL,                  // Текст заголовка (для статус-бара не используется)
        WS_CHILD | WS_VISIBLE, // Стили: дочернее окно и видимое. Обратите внимание, мы убрали SBARS_SIZEGRIP,
        // чтобы не было ручки изменения размера в правом нижнем углу (мы решили не добавлять).
        0, 0, 0, 0,            // Позиция и размер – будут установлены автоматически при WM_SIZE
        hwndParent,            // Родительское окно – наш диалог
        (HMENU)0,              // Идентификатор – не нужен, так как мы обращаемся через сохранённый HWND
        hInst,                 // Дескриптор экземпляра
        NULL                   // Дополнительные данные – не используем
    );

    // Если создание успешно и переданные параметры валидны, настраиваем части.
    if (hwndStatus && partsCount > 0 && partsWidths != NULL)
    {
        // Отправляем сообщение SB_SETPARTS, чтобы разделить статус-бар на части.
        // Параметры:
        //   wParam = partsCount – количество частей
        //   lParam = (LPARAM)partsWidths – указатель на массив ширин
        SendMessage(hwndStatus, SB_SETPARTS, partsCount, (LPARAM)partsWidths);

        // Устанавливаем начальный текст в первой части (индекс 0) – "Ready".
        // SB_SETTEXT – сообщение для установки текста в части.
        // wParam = 0 – индекс части, lParam = указатель на строку.
        SendMessage(hwndStatus, SB_SETTEXT, 0, (LPARAM)L"Ready");
    }

    // Возвращаем созданный HWND (или NULL, если что-то пошло не так).
    return hwndStatus;
}